async function run() {
  console.log(`Starting generation for ${topics.length} topics (30 scripts total)...`);
  let totalErrors = 0;
  let fileCount = 0;

  for (const topic of topics) {
    const topicDir = path.join(TARGET_BASE, topic.folder);
    if (!fs.existsSync(topicDir)) {
      fs.mkdirSync(topicDir, { recursive: true });
    }

    for (const script of topic.scripts) {
      fileCount++;
      const fileName = `${topic.id}-${topic.name}-${script.version}-${script.type}.txt`;
      const filePath = path.join(topicDir, fileName);

      // Validate lines
      const errors = [];
      script.lines.forEach((line, idx) => {
        const lineNum = idx + 1;
        if (line.length > 50) {
          errors.push(`Line ${lineNum} exceeds 50 chars (${line.length}): "${line}"`);
        }
        if (hasDigitsOrLatin(line)) {
          errors.push(`Line ${lineNum} has digits/latin: "${line}"`);
        }
      });

      if (errors.length > 0) {
        console.error(`[ERROR] Validation failed for ${fileName}:`);
        errors.forEach(e => console.error(`  - ${e}`));
        totalErrors += errors.length;
      }

      const content = script.lines.join('\n') + '\n';
      fs.writeFileSync(filePath, content, 'utf8');
      console.log(`[OK] Saved ${fileName} (${content.length} chars, ${script.lines.length} lines)`);
    }
  }

  console.log(`\nFinished writing ${fileCount} files. Total line-level validation errors: ${totalErrors}`);
  if (totalErrors > 0) {
    process.exit(1);
  }
}

run().catch(err => {
  console.error(err);
  process.exit(1);
});
