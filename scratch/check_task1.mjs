// Collision check against docs/风格/老王 and docs/风格/老王/样稿
import path from 'path';

function checkCollision(dir) {
  const h = s => s.replace(/[^一-龥]/g, '');
  const g = new Map();
  for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.txt'))) {
    const t = h(fs.readFileSync(path.join(dir, f), 'utf8').split('\n').slice(1).join(''));
    for (let i = 0; i + 8 <= t.length; i++) g.set(t.slice(i, i + 8), f);
  }
  let n = 0;
  lines.forEach((l, k) => {
    const t = h(l);
    for (let i = 0; i + 8 <= t.length; i++) {
      const s = t.slice(i, i + 8);
      if (g.has(s)) {
        n++;
        console.log(`[Collision in ${dir}] Line ${k + 1} 「${s}」 hit ${g.get(s)}`);
        break;
      }
    }
  });
  console.log(n ? `[${dir}] Overlap ${n} lines` : `[${dir}] 8-char collision 0`);
}

checkCollision('docs/风格/老王');
