for (const item of items) {
  const dir = path.join('research-runs/每日', '20261011-' + item.topic);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  const txtName = '20261011-' + item.topic + '-' + item.skin + '-' + item.o + '.txt';
  const metaName = '20261011-' + item.topic + '-' + item.skin + '-' + item.o + '.meta.json';

  const metaObj = {
    skin: item.skin,
    orientation: item.o,
    lengthTarget: '1-2min',
    date: '2026-10-11',
    topicSlug: item.slug,
    title: item.topic,
    style: '常规',
    titles: item.titles
  };

  const localTxt = path.join(dir, txtName);
  const localMeta = path.join(dir, metaName);

  fs.writeFileSync(localTxt, item.text.trim() + '\n', 'utf8');
  fs.writeFileSync(localMeta, JSON.stringify(metaObj, null, 2), 'utf8');

  // Copy to NAS
  const nasDir = path.join('Z:/素材生成库/ai文案/待审文案', item.topic);
  if (!fs.existsSync(nasDir)) fs.mkdirSync(nasDir, { recursive: true });
  fs.copyFileSync(localTxt, path.join(nasDir, txtName));
  fs.copyFileSync(localMeta, path.join(nasDir, metaName));

  // Run compliance check
  const comp = spawnSync('npm.cmd', ['run', 'check:compliance', '--', localTxt], { encoding: 'utf8', shell: true });
  const compPass = !comp.stdout.includes('BLOCK') && !comp.stdout.includes('block');

  // Run draft check
  const draft = spawnSync('npm.cmd', ['run', 'check:draft', '--', localTxt, '--topic', item.topic, '--topic-type', '虚拟'], { encoding: 'utf8', shell: true });
  const draftHits = (draft.stdout || '').split('\n').filter(l => l.includes('退回') && !l.includes('通过') && !l.includes('没跑') && !l.includes('人工'));

  results.push({
    topic: item.topic,
    skin: item.skin,
    chars: item.text.replace(/\s/g, '').length,
    compPass,
    draftFailCount: draftHits.length,
    draftHits
  });
}

